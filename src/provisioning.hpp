#pragma once

#include <string>

#include "db.hpp"

namespace provisioning {

struct Identity {
    std::string ledger_id;
};

// MVP — один персональный леджер на пользователя, авто-создаваемый (план,
// п. 1.3): если у user_id ещё нет ни одного members, заводит новый леджер и
// делает его owner'ом. Круг пользователей ("только я / семья / публично")
// пока не решён — шаринг на несколько человек добавляется позже строкой в
// ledger_member, без смены схемы.
//
// Известный, принятый как есть предел: два УСТРОЙСТВА, впервые
// синхронизирующиеся ОДНОВРЕМЕННО под одним новым аккаунтом, теоретически
// могут создать два разных леджера (гонка "искали — не нашли — оба
// создают") — уникальный индекс в схеме не пускает двух owner'ов ОДНОГО
// леджера, но не пускает и создание второго леджера тем же пользователем.
// Для масштаба этого сервиса (один пользователь синкает с одного устройства
// за раз в подавляющем большинстве случаев) риск принят осознанно —
// блокировка на всё время первого провижининга усложнила бы код ради
// исчезающе редкого случая.
//
// device_id/platform — из уже проверенного токена (session::User), не из
// тела запроса: доверяем только тому, что подписал google-auth. name —
// опционально, из тела запроса конкретного вызова, только для показа
// человеку (см. README google-auth, "Детали устройства").
Identity ensure_identity(db::Database& db, const std::string& user_id, const std::string& email,
                          const std::string& device_id, const std::string& device_name,
                          const std::string& platform);

} // namespace provisioning
